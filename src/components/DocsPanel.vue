            <h3>保护方式</h3>
            <ul>
              <li><b>无（种子内嵌）</b>：钥匙就写在文件里，任何人拿到图都能还原。它属于<b>混淆</b>，只有"防随手一看"的价值，<b>请勿用于敏感内容</b>。</li>
              <li><b>口令</b>：用你输入的口令派生出钥匙（PBKDF2-SHA256，盐值随机、迭代可调），文件里<b>不含任何钥匙材料</b>。不知道口令就还原不了——<b>忘记口令同样无法找回</b>，本工具不提供任何后门或找回途径。</li>
              <li><b>密钥文件（.ivkey）</b>：加密时生成 32 字节随机种子，在结果区手动下载成 <code>.ivkey</code>（多行文本：格式头 + 创建时间 + 密钥指纹 + Base64 种子）。解密时把它拖进凭据区即可，<b>无需关心任何参数</b>。强度高于一般人类口令。<b>丢失即无法还原，泄露即等同失守</b>；批量加密时整批共用一枚。</li>
              <li><b>怎么选</b>：随手保护用「口令」；重要资料或想要机器级强度用「密钥文件」；「无」只用于不敏感内容。</li>
              <li><b>强度直觉</b>：口令的强度取决于它有多难猜（长度、是否随机）；密钥文件的强度取决于那 32 个随机字节，与"好不好记"无关，所以它更强。</li>
            </ul>

            <h3>强度评估</h3>
            <ul>
              <li><b>按保护方式看</b>：
                <ul>
                  <li><b>无保护</b>：混淆（非加密）。拿到图就能还原，只是降低"随手一看"的可见度。</li>
                  <li><b>口令</b>：高。口令需要正确、且要付出迭代次数的计算代价才能得到钥匙；不知道口令无法还原。</li>
                  <li><b>密钥文件</b>：高—极高。256 位纯随机钥匙，只要文件没泄露，攻击者面对的是与军用级加密同量级的搜索空间。</li>
                </ul>
              </li>
              <li><b>为什么拼图式攻击不成立</b>：像素级布局在打乱之前，先让每个字节与密钥流做异或，像素值被均匀化。边缘的连续性、颜色分布、分块之间的相关性这些"可借用的线索"都不再成立。载荷级则更进一步——可见像素根本不参与还原。</li>
              <li><b>为什么改像素也没用</b>：密钥流不跨图复用（每张图随机生成），所以不存在"两张图相减把钥匙消掉"的做法；而任何像素改动都会被 HMAC 发现。</li>
              <li><b>强度的真正短板</b>：口令模式最终取决于口令本身有多难猜，弱口令仍可能被逐个试出来；文件结构上仍能看出"它经过本工具处理"（但看不出内容与参数）；口令和密钥文件怎么保管、怎么传递，超出了工具本身能保护的范围。</li>
            </ul>
          </div>


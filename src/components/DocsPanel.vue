              <li><b>按场景选</b>：只想"别人看不出内容、自己随时还原" → 覆盖合成；想输出一张可辨认的密文噪声图 → 密文混淆（默认载荷级）；既像正常照片、又不想在像素层留痕 → 密文 + 覆盖；仅降低随手查看的可见度 → 无保护混淆，切勿用于敏感数据。</li>
              <li><b>体积</b>：载荷级密文混淆、覆盖合成与多图合并的输出，基本就是「原文件本身 + 一张小尺寸的装饰/遮盖图」，通常只比原文件大百分之几。像素级与混合方式的可见像素不可压缩，体积明显更大（约 4 字节/像素）。</li>

          <div v-show="active === 'strength'" class="doc-sec">
            <h3>强度评估</h3>
            <ul>
              <li><b>分层结论</b>：
                <ul>
                  <li><b>无保护</b>：混淆（非加密）。持图即可还原，仅降低"随手一看"的可见度。</li>
                  <li><b>口令</b>：高。PBKDF2-SHA256 派生 + ChaCha20 密钥流加密，未知口令无法还原。</li>
                  <li><b>密钥文件</b>：高—极高。256 位全熵密钥，密钥文件不泄露时，攻击者面对的是与真加密（AES 类）等价的搜索空间。</li>
                </ul>
              </li>
              <li><b>为何抗拼图攻击</b>：像素级布局下，像素在置换之前先与密钥流逐字节异或，像素值被均匀化，边缘连续性、直方图、分块相关性等先验全部失效；"分块置换单独可解"的拼图类攻击在此不成立。载荷级布局更进一步，可见像素根本不参与还原。</li>
              <li><b>密钥流不跨图复用</b>：逐图随机 IV 保证同一密钥加密多张图、或多批次加密，均使用不同密钥流，杜绝"两图相异或消密钥"类攻击。</li>
              <li><b>篡改可检测</b>：HMAC 覆盖密文像素，任何像素改动都会在解密校验阶段被拒绝。</li>
              <li><b>局限与边界</b>：口令模式的最终强度取决于口令熵与迭代成本，弱口令仍可被离线爆破；文件仍带一个私有数据块，专业分析仍可判断它"经过本工具处理"（但不泄露内容与参数）；密钥/口令的保管与传输安全超出工具本身能力。</li>
            </ul>

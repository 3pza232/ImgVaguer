          <div v-show="active === 'mode'" class="doc-sec">
            <h3>混淆方式</h3>
            <ul>
              <li><b>密文混淆</b>：输出是一张<b>噪声图</b>——看得出"被处理过"，但看不出是什么。原图完整地存进文件内部。
                <ul>
                  <li><b>载荷级（推荐）</b>：原图以<b>原始文件字节</b>加密存放，解密后得到的文件与原文件完全一致（格式、清晰度、体积都一样）。可见的那张噪声图尺寸是独立的，<b>连原图多大都不会泄露</b>。速度最快，输出体积也与原文件相当。</li>
                  <li><b>像素级</b>：不做"行李箱"，直接把画面本身逐像素打乱（通道置换 → 异或流 → [S 盒替换] → 加性噪声 → [行列移位] → 块内与块间置换 → [全局像素置换]，方括号项可自由叠加）。解密是由像素反推回图片。代价是体积约为 4 字节/像素，明显更大，也慢得多。</li>
                </ul>
                两种布局都<b>逐位无损</b>，且每次加密都重新生成随机值，同一口令加密多张图也绝不会共用同一段密钥流。
              </li>
              <li><b>覆盖合成</b>：用一张或多张混淆图把目标图<b>盖住</b>，输出就是那张正常图片。原图同样完整存进文件内部。混淆图只负责"看上去像什么"，不参与还原。</li>
              <li><b>密文 + 覆盖（混合）</b>：先做像素级密文混淆，再把混淆图层盖上去。第一眼看到的是图层；但如果有人把图层褪掉、或把不透明度调成半透明（例如在图片软件里反解混合），露出来的是<b>密文噪声而不是原图</b>。适合"既要看起来正常、又不想在像素层留下原图痕迹"的场合，耗时约等于前两者相加，原图仍逐位无损还原。
                <ul>
                  <li><b>为什么没有「可见像素布局」可选</b>：像素级布局的含义是"密文直接驻留在可见像素里、不另存载荷"，而混合方式的图层会盖住像素，像素里的密文随之被破坏。因此混合方式的原图只能走加密载荷，可见像素布局固定为<b>载荷级</b>——这与纯密文混淆不同，不是功能缺失。</li>
                </ul>
              </li>
              <li><b>三者的取舍</b>：想让人一眼看出"这是密文"→ 密文混淆；想让输出像一张正常照片 → 覆盖合成；想两者都要 → 混合方式（耗时约等于前两者相加）。</li>
              <li><b>多层与目标层位</b>：图层条<b>自上而下显示，L1 在最上层</b>。拖动（移动端用 ↑↓）可调整层序。「目标图所在层」按自上而下的层号选择真图插在哪里——选「第 1 层（顶层）」真图会压在全部图层之上（肉眼可见），选「底层」（默认）则被完全盖住。</li>
              <li><b>覆盖层压缩</b>：降低图层细节以减小输出体积。它只影响遮盖层的观感，与原图还原精度无关。</li>
              <li><b>多图合并</b>：勾选输入区底部的开关后，本批全部目标图会合并输出成<b>一张图</b>（可见图取首图 / 装饰噪声 / 遮盖图）。所有原文件都装进同一份加密载荷，解密时会自动还原成原来的多张（混淆图不参与）。合并标志也是加密存放的，解密端凭同一凭据自动识别；三种保护方式都支持。</li>
            </ul>
          </div>


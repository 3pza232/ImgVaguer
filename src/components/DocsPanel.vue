            <h3>强度评估</h3>
            <ul>
              <li><b>分层结论</b>：
                <ul>
                  <li><b>无保护</b>：混淆（非加密）。持图即可还原，仅降低"随手一看"的可见度。</li>
                  <li><b>口令</b>：高。PBKDF2-SHA256 派生 + ChaCha20 密钥流加密，未知口令无法还原。</li>
                  <li><b>密钥文件</b>：高—极高。256 位全熵密钥，密钥文件不泄露时，攻击者面对的是与真加密（AES 类）等价的搜索空间。</li>

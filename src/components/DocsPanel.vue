            <ul>
              <li><b>KDF 迭代次数</b>：PBKDF2 迭代数，决定暴力破解每次猜测的成本。20 万为平衡点；高价值场景建议 100 万以上（加密前会有可感知耗时）。仅作用于口令保护；密钥文件与「无」使用全熵种子，派生不经过迭代拉伸。</li>
              <li><b>可见像素布局</b>（混淆）：载荷级的可见像素不承载密文，解密还原的是原文件本身；像素级的可见像素即密文，解密由像素还原为 PNG，故体积大得多。切换布局不影响无损性与安全强度。</li>
              <li><b>分块尺寸</b>（像素级）：置换块边长。8px 细碎、32px 粗快；边缘非整块仅参与块间置换。</li>

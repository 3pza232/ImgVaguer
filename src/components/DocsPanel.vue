              <li><b>S 盒字节替换</b>（像素级）：密钥化 256 置换表对 RGB 字节做非线性替换，对抗线性/差分分析。</li>
              <li><b>行列循环移位</b>（像素级）：每行/列按密钥循环平移，打破跨块空间相关性。</li>
              <li><b>全局像素置换</b>（像素级）：在整块与块内两级做密钥化洗牌，消除局部统计特征；&gt;8MP 大图明显变慢。</li>
              <li><b>覆盖不透明度</b>（覆盖）：覆盖层混合比例，100% 为完全不透明。</li>

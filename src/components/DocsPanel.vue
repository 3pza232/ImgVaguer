            <h3>混淆方式</h3>
            <ul>
              <li><b>密文混淆</b>：输出为<b>噪声状图像</b>，两种可见像素布局：
                <ul>
                  <li><b>载荷级（推荐）</b>：原图以<b>原始文件字节</b>加密存入 PNG 私有数据块，解密即还原原文件——格式、清晰度与体积都与输入一致。可见像素只是密钥化的装饰噪声，其尺寸独立于原图（不泄露原图尺寸），故输出体积与原文件相当，速度也快得多。</li>
                  <li><b>像素级</b>：可见像素即密文，经「通道置换 → 异或流 → [S 盒替换] → 加性噪声 → [行列移位] → 块内置换与双面体变换 → 块间置换 → [全局像素置换]」逐像素可逆变换，无独立载荷，方括号项可自由叠加；解密由像素还原为 PNG，体积约为 4 字节/像素。</li>
                </ul>
                两种布局均<b>逐位无损还原</b>，且每次加密生成独立随机 IV，同一密钥下的各张图像绝不共享密钥流。</li>
              <li><b>覆盖合成</b>：将一张或多张覆盖图按层叠放在目标图上形成视觉遮盖；原图以原始文件字节经 ChaCha20 加密后存入 PNG 私有数据块，解密即还原原文件。覆盖图仅作视觉遮盖，不参与还原。</li>
              <li><b>多层覆盖与目标层位</b>：覆盖图按 L1→Ln 顺序叠放；「目标图所在层」以自上而下层号选择真图插入位置——顶层表示真图压在所有覆盖图之上（可见），底层表示被完全遮盖（推荐）。</li>
              <li><b>覆盖层压缩</b>：降低覆盖层细节可显著减小覆盖层体积；仅影响遮盖层视觉效果，不影响原图还原精度。</li>
              <li><b>两种方式的取舍</b>：密文混淆输出为可辨认的"噪声图"，观感可疑；覆盖合成输出是一张"正常图片"，隐蔽性更好，但需要合适的覆盖图与层位设置。</li>
              <li><b>多图合并</b>：勾选「输入」区底部的开关后，本批所有目标图合并输出为<b>一张图</b>——载荷布局与覆盖合成下可见图为装饰噪声或遮盖图，像素布局下为「首图打乱」的噪声图。全部原文件装入加密载荷，解密时自动逐一还原（不含遮盖图）。合并标志随元数据加密，解密端凭同一凭据自动识别；无 / 口令 / 密钥文件三种保护均可用。</li>
            </ul>

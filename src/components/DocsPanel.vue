            <h3>保护方式</h3>
            <ul>
              <li><b>无（种子内嵌）</b>：随机种子写入图像数据块，持图即可一键还原。属于<b>混淆而非加密</b>，仅用于防君子不防小人的场合。</li>
              <li><b>口令</b>：PBKDF2-SHA256（盐值随机、迭代可调）派生主密钥，头部不含任何密钥材料。未知口令无法还原；<b>忘记口令即无法还原</b>。</li>
              <li><b>密钥文件（.ivkey）</b>：加密时生成 32 字节随机种子，在结果区手动下载为 <code>.ivkey</code> 文件（多行文本：格式头 + 创建时间 + 密钥指纹 + Base64 种子）。解密时将其拖入凭据区即可，<b>无需关心任何参数</b>。强度高于一般人类口令；请与加密图分开保管，丢失即无法还原，泄露即等同失守。批量加密时整批共用一枚密钥文件。</li>
              <li><b>如何选择</b>：日常便捷用口令；高价值数据或需要机器级强度时用密钥文件；「无」仅用于不敏感内容。</li>

            <h3>名词解释</h3>
            <ul>
              <li><b>混淆 vs 加密</b>：<b>加密</b>是靠钥匙才能读；<b>混淆</b>只是让人一眼看不出内容，没有钥匙也能还原。「无保护」档属于后者，本工具其余档位都带真正的加密。</li>
              <li><b>载荷（payload）</b>：藏在文件内部的那份真正内容。可以把它想成<b>行李箱里的东西</b>——外面看的是一张图，箱子里的原图才是要保护的对象。</li>
              <li><b>可见像素</b>：别人打开文件时看到的那张图，相当于<b>行李箱的外壳</b>。它可以是噪声、遮盖图，甚至与原图毫无关系；只要载荷在，还原就不受影响。</li>
              <li><b>还原 / 逐位无损</b>：还原指把载荷取出、拼回原始文件。<b>逐位无损</b>意味着取出后的文件与原文件一个字节都不差（不是"看起来差不多"），文件名与格式也保持不变。</li>
              <li><b>重编码</b>：用画图、截图、社交软件转发时，图片会被重新压缩、重新存一遍，这一步会破坏文件内部结构。本工具的输出<b>不能</b>经过重编码，必须原样发送。</li>
              <li><b>口令 / 密钥文件 / 种子</b>：<b>口令</b>是你想得起来的一串字；<b>密钥文件</b>是程序生成的 32 字节随机数（写成一个 <code>.ivkey</code> 文本文件），猜不出来；<b>种子</b>就是这个随机数的本身。</li>
              <li><b>密钥派生（KDF）、迭代次数、盐</b>：<b>密钥派生</b>是把口令"揉"成一把真正可用的钥匙的过程——口令本身不能直接当钥匙用。<b>迭代次数</b>就是"揉"多少遍：揉得越多，别人逐个试口令就越慢。<b>盐</b>是一段随机值，保证即便两个人用同一个口令，也不会得到同一把钥匙。</li>
              <li><b>HMAC（完整性校验）</b>：相当于贴在文件上的<b>防拆封条</b>。文件（包括像素）被任何人改动过，解密时都会被发现并明确报错，而不会给你一张错图。</li>
              <li><b>像素 / 通道 / 不透明度</b>：一张图由许多小方块（像素）拼成，每个像素由红、绿、蓝、透明四个数值描述（即四个<b>通道</b>）。<b>不透明度</b>就是两个图层叠在一起时，上层盖住下层的比例。</li>
              <li><b>元数据（EXIF）</b>：照片里除画面之外附带的信息，比如拍摄时间、机型、GPS 位置。它跟着文件走，别人拿到图就能读到。</li>
              <li><b>图层与层序</b>：多个混淆图叠在一起时，每一张称为一个<b>图层</b>；谁盖住谁是<b>层序</b>。本工具中图层条自上而下显示，<b>L1 在最上层</b>。</li>
              <li><b>PNG 数据块</b>：PNG 文件由若干"数据块"拼成，其中有些块是留给程序自定义用的。本工具就把加密后的内容放在这样一个自定义块里，其他看图软件会忽略它、只显示可见像素。</li>
              <li><b>四段耗时</b>：结果区的「性能分析」把一批任务的时间拆成四段——<b>密钥派生</b>（由口令或密钥文件推出密钥）、<b>载荷处理</b>（打包压缩与加解密）、<b>像素处理</b>（位图解码与混淆 / 合成）、<b>输出封装</b>（PNG 编码、预览与落地）；此外还有一段<b>图层与批级开销</b>（不使用图层的方式显示为「批级开销」），等于批次总耗时减去各张耗时之和——它包含整批共用的图层解码与界面刷新等，<b>但不含</b>你手动点击的导出 / 打包，那是执行结束后另外发生的动作。</li>
            </ul>

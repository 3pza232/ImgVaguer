          <div v-show="active === 'params'" class="doc-sec">
            <h3>参数详解</h3>
            <ul>
              <li><b>KDF 迭代次数</b>（仅口令）：把口令"揉"成钥匙要揉多少遍。揉得多，暴力试口令的成本就高，代价是加密时多等一会儿。<b>20 万是平衡点</b>；高价值内容可用 100 万以上（会有可感知的等待）。密钥文件与「无保护」用的是全随机种子，不需要揉，所以几乎瞬时。</li>
              <li><b>可见像素布局</b>（密文混淆）：决定"外壳"怎么做，不影响内容与强度。载荷级外壳是装饰噪声、体积小、速度快；像素级外壳本身就是密文，体积约 4 字节/像素。拿不准就用载荷级。</li>
              <li><b>分块尺寸</b>（像素级 / 混合）：打乱的最小单位。8px 打得更碎，32px 更快。边缘不足一块的部分只参与块间打乱。</li>
              <li><b>噪声强度</b>（像素级 / 混合）：给像素值加上可逆的随机扰动（0–64），把"哪些颜色多、哪些颜色少"这类统计特征抹平；0 表示关闭。</li>
              <li><b>变换轮数</b>（像素级 / 混合）：整套打乱重复 1–4 遍，每一遍用的是不同密钥流，因此多轮确实更难还原。轮数越多越慢。</li>
              <li><b>S 盒字节替换</b>（像素级 / 混合）：用一张由密钥决定的替换表，把每个颜色字节换成另一个值。它让"输入变一点、输出变很多"这种非线性关系成立，专门对付线性与差分分析。</li>
              <li><b>行列循环移位</b>（像素级 / 混合）：整行整列地错位，打破上下左右相邻像素的关联。</li>
              <li><b>全局像素置换</b>（像素级 / 混合）：在全图范围做密钥化洗牌，把局部规律彻底打散；超过约 800 万像素的图会明显变慢。</li>
              <li><b>覆盖不透明度</b>（覆盖 / 混合）：图层盖住目标图的力度，100% 表示完全盖住。混合方式下把它调低一些，可以做出"半透的图层 + 隐约的密文底纹"的效果。</li>
              <li><b>覆盖层压缩</b>（覆盖 / 混合）：10%–100%，降低图层细节以减小输出体积。只影响外观，不影响还原。</li>
              <li><b>覆盖图适配</b>（覆盖 / 混合）：目标尺寸与图层比例不一致时，等比裁剪（填满画面、裁掉多余边缘）或拉伸填充（画面完整但可能变形）。</li>
              <li><b>参数存在哪</b>：混淆方式、保护方式与上述全部参数都随元数据加密写进图片，解密端自动读取——所以解密时只需要凭据，不需要回忆参数。</li>
            </ul>
          </div>

          <div v-show="active === 'security'" class="doc-sec">
            <h3>安全模型</h3>
            <ul>
              <li><b>用什么算法</b>：ChaCha20（RFC 8439，经官方测试向量校验）做密钥流加密，PBKDF2-SHA256 派生口令密钥，HKDF-SHA256 处理全随机种子，HMAC-SHA256 做完整性校验。均为公开、经过长期检验的标准算法。</li>
              <li><b>一把钥匙分六份用</b>：主密钥按用途展开为 6 个互不相干的子密钥（置换 / 异或流 / 噪声 / MAC / 载荷 / 元数据），每个子步骤、每一轮、每种载荷各有独立的随机域——同一把钥匙的不同用途之间不会互相削弱。</li>
              <li><b>每张图都换新密钥流</b>：每次加密都会生成随机 salt，据此决定该图的密钥流起点。因此同一口令加密一批图，彼此之间也不存在"两图相减抵消钥匙"的可能。</li>
              <li><b>公开字段只剩必要信息</b>：文件里能被直接读到的只有格式版本、salt、迭代次数与一段随机种子（这三种保护方式的种子长度相同，单看文件无法分辨用的是哪种）。<b>混淆方式、原图尺寸、全部参数与内容本身都是加密存放的</b>，文件里也没有工具品牌标识。</li>
              <li><b>改一个像素都能发现</b>：HMAC 覆盖公开前导、加密元数据与真正承载密文的那一部分。口令或密钥不对、文件被篡改（哪怕只改了一个像素）都会明确报错，不会输出一张错图。</li>
              <li><b>还原不经过滤镜</b>：载荷级直接返回原始文件字节；像素级走内置 PNG 解码器逐位还原，不经过画布的色彩管理与预乘处理，带透明通道的图也能精确校验。</li>
              <li><b>威胁模型（能防什么、不能防什么）</b>：本工具的目标是「内容不可读 + 可校验还原 + 全程离线」。它能防住拿到文件的人；防不住弱口令被离线暴破，也不承诺不可否认性或隐写级的"看不出被处理过"。</li>
              <li><b>全程离线</b>：所有计算都在本机完成，图片、口令与密钥文件不经过任何网络传输。</li>
            </ul>

            <h3>混淆方式</h3>
            <ul>
              <li><b>密文混淆</b>：像素级密钥化可逆变换管线：通道置换 → 异或流 → [S 盒替换] → 加性噪声 → [行列移位] → 块内置换与双面体变换 → 块间置换 → [全局像素置换]。方括号项可自由叠加。全程双射，<b>逐位无损还原</b>，输出呈均匀噪声状；每次加密生成独立随机 IV，同一密钥下的各张图像绝不共享密钥流。</li>
              <li><b>覆盖合成</b>：将一张或多张覆盖图按层叠放在目标图上形成视觉遮盖；原图经 zlib 压缩 + ChaCha20 加密后存入 PNG 私有数据块，还原时整体取回，逐位无损。覆盖图仅作视觉遮盖，不参与还原。</li>
              <li><b>多层覆盖与目标层位</b>：覆盖图按 L1→Ln 顺序叠放；「目标图所在层」以自上而下层号选择真图插入位置——顶层表示真图压在所有覆盖图之上（可见），底层表示被完全遮盖（推荐）。</li>

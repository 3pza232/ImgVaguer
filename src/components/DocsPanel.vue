          <div v-show="active === 'security'" class="doc-sec">
            <h3>安全模型</h3>
            <ul>
              <li>原语：ChaCha20（RFC 8439，经官方测试向量校验）密钥流、PBKDF2-SHA256、HKDF-SHA256、HMAC-SHA256。</li>
              <li>主密钥按用途展开为 6 个独立子密钥（置换 / 异或流 / 噪声 / MAC / 载荷 / 元数据），避免跨域复用；每个子步骤、每一轮与每种载荷类型使用独立 nonce 域。</li>
              <li>逐图随机 IV：每次加密生成随机 salt，取前 11 字节填入各行 nonce，与密钥域共同决定唯一密钥流；同一密钥下的不同图像（含批量加密整批）不会发生密钥流复用。</li>
              <li>元数据加密 / 去指纹：公开字段仅保留引导密钥派生所需的 version/salt/迭代数/随机种子；<b>模式、布局、保护方式、分块/噪声参数、原图尺寸与载荷全部加密</b>存放，文件中不再含工具品牌标识。</li>
              <li>保护方式不可区分：三种保护方式统一为「字节凭据 → 主密钥」，且公开 seed 恒为等长随机，因此单看文件无法分辨其用的是口令、密钥文件还是内嵌种子。</li>
              <li>凭据派生：口令走 PBKDF2-SHA256 迭代拉伸以抬高枚举成本；密钥文件种子与内嵌种子为 256 位全熵，走 HKDF-SHA256（迭代拉伸对高熵密钥没有强度增益，只会平白耗时）。</li>
              <li>完整性：HMAC-SHA256 覆盖公开前导、加密元数据与<b>密文像素</b>，口令/密钥错误或文件被篡改（含像素改动）会明确报错，绝不输出乱图。载荷版布局下，原图整块受密钥流加密与同一条 HMAC 保护。</li>
              <li>完整还原：载荷级布局下解密直接返回原始文件字节，逐字节一致；像素级布局下解密经内置 PNG 解码器逐位还原，不经 canvas 的色彩管理与预乘处理，含透明通道亦精确可校验。</li>
              <li>威胁模型：本工具的目标是「内容不可读 + 可校验还原 + 全程离线」，不追求对抗拥有无限算力的对手，也不提供不可否认性或隐写伪装。</li>
              <li>全部计算在本机浏览器内完成，图像、口令与密钥文件不经过任何网络传输。</li>
            </ul>

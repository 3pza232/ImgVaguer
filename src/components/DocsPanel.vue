          <div v-show="active === 'tips'" class="doc-sec">
            <h3>使用建议</h3>
            <ul>
              <li><b>口令</b>：优先使用 12 位以上随机口令或长口令短语；迭代次数 20 万起，高价值数据用 100 万以上。</li>
              <li><b>密钥文件</b>：与加密图分开存放（不同设备 / 云盘），泄露即等同失守；批量加密同一批共用一枚便于分级管理。</li>
              <li><b>传输</b>：务必发送原始 PNG 文件（或打包 ZIP），避免走会重编码的渠道（截图、社交软件压图、在线转码）。</li>
              <li><b>备份</b>：加密前保留原图，加密后保留输出 PNG 与凭据，三者缺一不可。</li>
              <li><b>场景选择</b>：只想"别人看不出内容、自己可还原" → 覆盖合成；想要"输出为噪声图" → 密文混淆（默认载荷级）；仅想降低随手查看的可见度 → 无保护混淆即可，切勿用于敏感数据。</li>
              <li><b>体积</b>：载荷级密文混淆、覆盖合成与多图合并的输出就是「原文件 + 一张小尺寸装饰图 / 遮盖图」，通常只比原文件大百分之几。像素级密文混淆的可见像素不可压缩，体积约为 4 字节/像素，仅在需要"密文完全驻留像素"时使用。</li>
              <li><b>性能</b>：载荷级与覆盖合成只需读取原文件字节并做一次轻度压缩，与图片内容无关，大图也很快；像素级按像素数线性增长，「全局像素置换」「多轮」「S 盒」「行列移位」在移动端大图上明显变慢。</li>
            </ul>
          </div>

          <div v-show="active === 'faq'" class="doc-sec">
            <h3>注意事项</h3>
            <ul>
              <li>输出统一为 PNG（内含私有数据块）。<b>经其他编辑器另存、压缩或转格式会丢失数据块</b>，无法还原——请妥善保管原始输出。</li>
              <li>截图、社交软件转发压缩同样会破坏数据；还原需使用原始输出文件。</li>
              <li><b>本版加密与解密配套</b>：请使用同一版本加密与解密，版本不符时会明确提示，不会静默产出错误结果。</li>
              <li>载荷级布局还原的是<b>原始文件本身</b>，原文件的元数据（如 EXIF 拍摄信息、GPS）也一并保存在加密载荷中。若需去除元数据，请先自行清理原图再加密，或改用像素级布局——其载荷为解码后的位图，不含任何元数据。</li>
              <li><b>合并体积</b>：多图合并的输出体积约等于各原文件之和（原文件多已压缩，二次压缩收益有限），张数越多输出越大。张数上限（{{ TARGET_MIN }}–{{ TARGET_MAX }} 张）、覆盖图层数（{{ COVER_MIN }}–{{ COVER_MAX }} 层）与单张像素上限可在「设置 → 批量上限」调整，超限的图像不会载入并在日志中说明原因。</li>
              <li><b>载入与内存</b>：载入图像时只读取尺寸，位图推迟到加密时才按需解码，因此批量载入大图不会因内存不足而失败——像素级布局与覆盖合成才需要真实像素。</li>
              <li>批量加密若使用密钥文件保护，整批共用一枚密钥文件；建议不同批次分开加密以便分级管理。</li>
              <li>「默认口令」以明文存于 localStorage；「记住参数」会保存全部参数与保护方式。公共设备离开前请清理。</li>
              <li>保护方式会记住上次选择，首次使用默认<b>口令</b>；在设置里填写默认口令后，切到口令模式且输入框为空时会自动填入。「无（种子内嵌）」持图即可还原，仅用于防君子场景。</li>
              <li>本工具不修改像素以外的元数据来源：还原结果以像素为准，逐位一致；如遇图像打不开或尺寸异常，通常是文件在传输中被破坏。</li>
            </ul>

          <div v-show="active === 'tips'" class="doc-sec">
            <h3>使用建议</h3>
            <ul>
              <li><b>口令</b>：优先使用 12 位以上随机口令或长口令短语；迭代次数 20 万起，高价值数据用 100 万以上。</li>
              <li><b>密钥文件</b>：与加密图分开存放（不同设备 / 云盘），泄露即等同失守；批量加密同一批共用一枚便于分级管理。</li>
              <li><b>传输</b>：务必发送原始 PNG 文件（或打包 ZIP），避免走会重编码的渠道（截图、社交软件压图、在线转码）。</li>
              <li><b>备份</b>：加密前保留原图，加密后保留输出 PNG 与凭据，三者缺一不可。</li>
              <li><b>场景选择</b>：只想"别人看不出内容、自己可还原" → 覆盖合成；想要"输出为强噪声图" → 密文混淆；仅想降低随手查看的可见度 → 无保护混淆即可，切勿用于敏感数据。</li>
              <li><b>性能与体积</b>：1080p 基础管线约百毫秒级；全局像素置换与多轮按像素数线性增长，大图明显变慢。输出为噪声图时 PNG 压缩率低，文件通常大于原图，覆盖合成可用「覆盖层压缩」减小体积。</li>
            </ul>

              <li><b>两种方式的取舍</b>：密文混淆输出为可辨认的"噪声图"，体积较大、观感可疑；覆盖合成输出是一张"正常图片"，隐蔽性更好，但需要合适的覆盖图与层位设置。</li>
              <li><b>多图合并</b>：勾选「输入」区底部的开关后，本批所有目标图合并输出为<b>一张图</b>——密文混淆时可见图为「首图打乱」的噪声图，覆盖合成时可见图为遮盖图。原图全部装入加密载荷，解密时自动展开为全部原图（不含遮盖图）。合并标志随元数据加密，解密端凭同一凭据自动识别；无 / 口令 / 密钥文件三种保护均可用。</li>
